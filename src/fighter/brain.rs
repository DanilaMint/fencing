// не вызывается — поэтому предупреждения о мёртвом коде отключены
#[allow(dead_code)]
pub mod strategist;

use crate::{fighter::action::Action, round::situation::Situation};

/// Событие, произошедшее с бойцом за последний тик.
///
/// События нужны мозгу, чтобы оценивать результат своих действий:
/// по ним можно понять, удалось ли нанести удар, отбит ли удар противника
/// и не потрачена ли энергия впустую.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum BrainEvent {
    /// Боец нанёс удар противнику. `power` — сила удара (импульс)
    HitDealt { power: f32 },
    /// Боец получил удар. `power` — сила удара (импульс)
    HitTaken { power: f32 },
    /// Клинки столкнулись: удары отражены, удар противника отбит
    Parried,
    /// Удар в голову: тело бойца временно не подчиняется
    Shocked,
    /// Боец потратил энергию на действие
    EnergySpent { amount: f32 },
}

pub trait Brain {
    fn get_actions(&mut self, situation: Situation) -> Action;

    /// Событие, произошедшее с бойцом.
    /// По умолчанию мозг его игнорирует, поэтому простые мозги
    /// (заглушка, управление игроком) менять не приходится.
    fn on_event(&mut self, _event: BrainEvent) {}

    /// Раунд закончился.
    ///
    /// Мозг, который помнит о боях (стратег), на этом шаге закрывает
    /// текущую реакцию: её результат должен попасть в рейтинг записи,
    /// а не смешаться с результатом следующего боя.
    ///
    /// По умолчанию ничего не делает: простым мозгам о боях помнить не о чем.
    fn on_round_end(&mut self) {}
}
