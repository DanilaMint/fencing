use crate::{fighter::brain::Brain, round::Round};

/// Раунд без окна: окно не создаётся, отрисовка не выполняется.
///
/// Бойцы играют теми мозгами, которые заданы флагами. Игрока здесь нет —
/// клавиатура и мышь в этом режиме недоступны, поэтому такой мозг
/// заменяется заглушкой ещё при сборке мозгов.
pub fn run(red: Box<dyn Brain>, blue: Box<dyn Brain>) {
    let mut round = Round::new(red, blue);

    // Тик после конца раунда ничего не делает, а сам раунд ограничен по времени,
    // поэтому цикл всегда конечен
    while !round.is_finished() {
        round.tick();
    }
}
